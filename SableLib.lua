					r.Visible = false
				else
					r.Parent = grid and win._gridScroll or win._scroll
				end
			end
		end
		win._gridScroll.Visible = grid
		win._scroll.Visible = not grid
		if grid then updateGridColumns(win) end
		syncPages(win)
		applyFilter(win)
		styleViewBtns(win)
	end
	local function applyView(win, animate)
		if not animate then doApplyView(win) return end
		win._viewToken = (win._viewToken or 0) + 1
		local tok = win._viewToken
		if win._currentPage then
			for _, r in ipairs(win._currentPage.Rows) do
				if r.Visible then
					tw(r, 0.07, { BackgroundTransparency = 1 })
					for _, d in ipairs(r:GetDescendants()) do
						if d:IsA("TextLabel") then tw(d, 0.07, { TextTransparency = 1 })
						elseif d:IsA("ImageLabel") then tw(d, 0.07, { ImageTransparency = 1 }) end
					end
				end
			end
		end
		task.delay(0.08, function()
			if win._viewToken ~= tok then return end
			doApplyView(win)
			animateCards(win)
		end)
	end

	function Window:SetView(v)
		v = (v == "grid") and "grid" or "list"
		if self._view == v then return end
		self._view = v
		applyView(self, true)
	end
	function Window:GetView() return self._view end

	-- Sidebar-Section (Gruppen-Label), z.B. "MODULES" oder custom "AUTO FARM"
	-- Wird automatisch angelegt; CreateSection legt sie vorab an (Reihenfolge!)
	local function ensureGroup(win, group)
		if group == nil or group == "" then return nil end
		group = tostring(group)
		if win._groups[group] then return group end
		win._groups[group] = true
		win._sideOrder = win._sideOrder + 1
		create("TextLabel", {
			Parent = win._sideList,
			Size = UDim2.new(1, 0, 0, 20),
			BackgroundTransparency = 1,
			Text = "  " .. string.upper(group),
			Font = Enum.Font.GothamMedium,
			TextSize = 11,
			TextColor3 = COLORS.Sub,
			TextXAlignment = Enum.TextXAlignment.Left,
			LayoutOrder = win._sideOrder,
		})
		return group
	end

	-- Header: "<n> modules - <m> enabled"
	local function refreshHeader(win)
		local tab = win._currentTab
		if not tab then return end
		fancyTitle(win._headerTitle, tab.Title or tab.Name)
		local total = tab.Count or 0
		if total == 0 then
			for _, p in ipairs(tab.Pages) do total = total + #p.Rows end
		end
		local en = 0
		for _, r in ipairs(win._toggleRegs) do
			if r.tab == tab then
				local ok, v = pcall(r.get)
				if ok and v then en = en + 1 end
			end
		end
		win._headerSub.Text = string.format("%d modules · %d enabled", total, en)
	end

