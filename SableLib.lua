			tw(shadow, 0.15, { BackgroundTransparency = 0.75 })
		else
			local sc = ensureScale(container)
			tw(sc, 0.16, { Scale = 0.98 })
			tw(container, 0.16, { Position = UDim2.new(0.5, 0, 0.5, 6) })
