local function fancyTitle(label, text)
	text = tostring(text or "")
	local esc = text:gsub("&", "&amp;"):gsub("<", "&lt;"):gsub(">", "&gt;")
	local first, rest = string.match(esc, "^(%S+)%s*(.-)%s*$")
	label.Font = TitleFont
	if rest and rest ~= "" then
		label.RichText = true
		label.Text = first .. ' <i><font color="rgb(190,185,235)">' .. rest .. "</font></i>"
	else
		label.RichText = false
		label.Text = esc
	end
end

local function isLucideName(s)
	if type(s) ~= "string" then return false end
	if s == "" then return false end
	if string.find(s, "rbxassetid", 1, true) then return false end
	-- lucide-namen sind lowercase mit bindestrich, keine leerzeichen/emojis
	if string.match(string.lower(s), "^[a-z0-9%-]+$") then return true end
	return false
end

local function create(className, props, children)
	local inst = Instance.new(className)
	for k, v in pairs(props or {}) do
		if k ~= "Parent" then
			pcall(function()
				inst[k] = v
			end)
		end
	end
	for _, child in ipairs(children or {}) do
		child.Parent = inst
	end
	if props and props.Parent then
		inst.Parent = props.Parent
	end
	return inst
end

