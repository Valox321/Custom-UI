								render(true)
							end
						end)
					end)
				end
				dragKnob(k1, true)
				dragKnob(k2, false)
				render(false)
				local api = {}
				function api:Get() return lo, hi end
				function api:Set(a, b)
					lo = math.clamp(a or lo, min, max)
					hi = math.clamp(b or hi, min, max)
